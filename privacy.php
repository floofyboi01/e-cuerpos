            <p>Lo que esta Pol&iacute;tica de Privacidad cubre:</p>
            <p>Esta pol&iacute;tica cubre como la E-Cuerpos trata las informaciones 
              personales que recoge y recibe, incluyendo las informaciones relacionadas 
              con los usos anteriores del cliente de los productos de la E-Cuerpos. 
              Informaci&oacute;n personal es la informaci&oacute;n sobre usted 
              que es personalmente identificable, como su nombre, direcci&oacute;n, 
              correo electr&oacute;nico o n&uacute;mero de tel&eacute;fono y que 
              no se encuentra disponible p&uacute;blicamente de ninguna otra manera.</p>
            <p>Colecta y Uso de la Informaci&oacute;n</p>
            <p>General<br>
              La E-Cuerpos recoge informaciones personales cuando usted se registra 
              en la E- Cuerpos.</p>
            <p>Cuando usted se registra, pedimos informaciones como su nombre, 
              correo electr&oacute;nico, fecha de nacimiento, sexo, CP, profesi&oacute;n, 
              mercado y intereses personales. Para algunos servicios y productos 
              financieros, tambi&eacute;n podremos pedir su direcci&oacute;n, 
              documento de identidad informaciones sobre sus posesiones. Una vez 
              que se registre junto a la E-Cuerpos y firme nuestros servicios, 
              usted no m&aacute;s ser&aacute; an&oacute;nimo para nosotros.<br>
              La E-Cuerpo recoge informaciones sobre sus negociaciones con nosotros 
              y con otros con los cuales mantenemos negociaciones, incluso informaciones 
              sobre su utilizaci&oacute;n de nuestros productos. <br>
              La E-Cuerpos utiliza la informaci&oacute;n para los siguientes prop&oacute;sitos 
              generales: personalizar los titulares y el contenido que usted ve, 
              atender su demanda de los productos, estar en contacto con usted, 
              conducir investigaciones y proporcionar informes an&oacute;nimos 
